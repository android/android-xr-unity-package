namespace Google.XR.Extensions
{
    using System.Diagnostics.CodeAnalysis;
    using Google.XR.Extensions.ARSubsystems;
    using UnityEngine;
    using UnityEngine.XR.ARFoundation;
    using UnityEngine.XR.ARSubsystems;

    /// <summary>
    /// Represents a shareable anchor tracked by an XR device.
    /// </summary>
    /// <remarks>
    /// Generated by the <see cref="ARShareableAnchorManager"/> when an XR
    /// device creates or loads a shareable anchor in the environment.
    /// </remarks>
    [SuppressMessage(
        "UnityRules.UnityStyleRules", "US1109:PublicPropertiesMustBeUpperCamelCase",
        Justification = "Match Unity interface.")]
    [DefaultExecutionOrder(ARUpdateOrder.k_Anchor + 1)]
    [DisallowMultipleComponent]
    public sealed class ARShareableAnchor : ARTrackable<XRShareableAnchor, ARShareableAnchor>
    {
        private bool _isGeospatialAnchor = false;
        private XRGeospatialSurfaceType _surfaceType = XRGeospatialSurfaceType.Default;
        private XRGeospatialPose _geospatialPose = default;

        /// <summary>
        /// Gets the host of this shareable anchor.
        /// </summary>
        public XRShareableAnchorHosts host =>
            _isGeospatialAnchor ? XRShareableAnchorHosts.Geospatial : sessionRelativeData.host;

        /// <summary>
        /// Gets the shareable ID to retrieve the anchor from other clients.
        /// </summary>
        public SerializableGuid shareableId => sessionRelativeData.shareableId;

        /// <summary>
        /// Gets the surface type of a geospatial anchor.
        /// It is only valid when <see cref="host"/> is
        /// <see cref="XRShareableAnchorHosts.Geospatial"/>.
        /// </summary>
        public XRGeospatialSurfaceType surfaceType => _surfaceType;

        /// <summary>
        /// Gets the geospatial pose where this anchor is placed.
        /// Combined with <see cref="surfaceType"/> to retrieve the same
        /// geospatial anchor from other clients.
        /// </summary>
        public XRGeospatialPose geospatialPose => _geospatialPose;

        internal void UpdateGeospatialAnchor(
            XRGeospatialSurfaceType surfaceType, XRGeospatialPose geospatialPose)
        {
            if (sessionRelativeData.host != XRShareableAnchorHosts.None &&
                sessionRelativeData.host != XRShareableAnchorHosts.Geospatial)
            {
#if DEBUG
                Debug.LogErrorFormat(
                    "Failed to update {0} to geospatial anchor, it has already been hosted by {1}.",
                    trackableId, sessionRelativeData.host);
#endif // DEBUG
                return;
            }

            _isGeospatialAnchor = true;
            _surfaceType = surfaceType;
            _geospatialPose = geospatialPose;
        }
    }
}
