namespace Google.XR.Extensions
{
    using UnityEngine;

    /// <summary>
    /// The strategy to configure Google Cloud authentication.
    /// </summary>
    public enum XRAuthenticationStrategy : int
    {
        /// <summary>
        /// Not in use.
        /// </summary>
        [InspectorName("None")]
        None = 0,

        /// <summary>
        /// Keyless strategy.
        /// </summary>
        /// <remarks>
        /// Credential is not required.
        /// The runtime may generate credentials dynamically and communicates
        /// with Google Play Services from the application process.
        /// </remarks>
        [InspectorName("Keyless")]
        Keyless = 1,

        /// <summary>
        /// API key strategy.
        /// </summary>
        /// <remarks>
        /// The credential must further satisfy the following conditions:
        /// <list type="bullet">
        /// <item><description>
        /// It must be a valid API Key generated for your Google Cloud project.
        /// </description></item>
        /// <item><description>
        /// Your Google Cloud project must enable the relevant Google Cloud APIs
        /// (specified by the OpenXR extensions).
        /// </description></item>
        /// <item><description>
        /// If the API Key has restrictions, the restrictions must allow the
        /// relevant Google Cloud APIs and your application.
        /// </description></item>
        /// </list>
        /// </remarks>
        [InspectorName("API Key")]
        ApiKey = 2,

        /// <summary>
        /// Authentication token strategy.
        /// </summary>
        /// <remarks>
        /// The credential of authentication token must be one of:
        /// <list type="bullet">
        /// <item><description>
        /// An OAuth2 access token with the relevant scopes, generated by
        /// signing into a Google account with your application.
        /// </description></item>
        /// <item><description>
        /// A Signed JWT token with the relevant claims, generated by a Service
        /// Account from your Google Cloud project.
        /// </description></item>
        /// </list>
        /// </remarks>
        [InspectorName("Authentication Token")]
        AuthToken = 3,
    }
}
